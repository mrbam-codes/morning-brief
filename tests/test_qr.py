"""QR test (plan 14). Run from the repository: python3 tests/test_qr.py

Checks that qr.js is the generated file for the ONE address constant, SITE in tools/build_qr.py:
- qr.js says it is generated, holds that address, and its printed label comes from it;
- the page prints the address from qr.js, never a typed-in copy;
- the grid in qr.js equals what the segno QR library makes for SITE at error correction Q,
  and that is the smallest version that holds it (skipped, not failed, when segno is missing).
Prints QR OK or the misses.
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.dont_write_bytecode = True  # no __pycache__ left in tools/
sys.path.insert(0, str(ROOT / "tools"))
import build_qr  # noqa: E402

misses = []


def need(ok, msg):
    print(("ok    " if ok else "MISS  ") + msg)
    if not ok:
        misses.append(msg)


js = (ROOT / "qr.js").read_text(encoding="utf-8")
m = re.search(r"window\.MBQR=(\{.*\});\s*$", js, re.S)
need(bool(m), "qr.js sets window.MBQR")
Q = json.loads(m.group(1)) if m else {}
need("GENERATED by tools/build_qr.py" in js and "Do not edit by hand" in js and "python3 tools/build_qr.py" in js, "qr.js says it is generated, not to hand-edit, and how to regenerate")
need(Q.get("url") == build_qr.SITE, f"qr.js address is SITE ({build_qr.SITE})")
need(Q.get("label") == build_qr.label(build_qr.SITE), f"qr.js label is SITE without https:// and the closing slash ({Q.get('label')})")
rows = Q.get("rows") or []
need(Q.get("ecc") == "Q" and rows and Q.get("size") == len(rows) == 17 + 4 * Q.get("version", 0) and all(re.fullmatch("[01]{%d}" % len(rows), r) for r in rows),
     f"grid is {len(rows)} by {len(rows)} ones and zeros for version {Q.get('version')}, error correction Q")

idx = (ROOT / "index.html").read_text(encoding="utf-8")
need('<script src="qr.js"></script>' in idx and idx.index('src="qr.js"') < idx.index('src="scorecard.js"'), "the page loads qr.js before scorecard.js")
need("url:window.MBQR?MBQR.label:''" in idx, "the address on the share card comes from qr.js")
host = build_qr.label(build_qr.SITE)
for f in ("index.html", "scorecard.js"):
    need(host not in (ROOT / f).read_text(encoding="utf-8"), f"{f} has no typed-in copy of the address")

try:
    import segno
except ImportError:
    segno = None
if segno is None:
    print("skip  segno is not installed here, so the grid was not compared (run with a Python that has segno)")
else:
    version, want = build_qr.grid(build_qr.SITE)
    need(rows == want, f"grid matches segno for {build_qr.SITE}")
    need(Q.get("version") == version, f"version {version} recorded")
    smaller = True
    if version > 1:
        try:
            segno.make(build_qr.SITE, error="q", boost_error=False, micro=False, mode="byte", version=version - 1)
        except Exception:
            smaller = False
    need(not smaller, f"version {version} is the smallest that holds the address at Q")

print("QR OK" if not misses else "MISSES: " + str(len(misses)))
sys.exit(1 if misses else 0)
