"""Build qr.js: the share card's QR code (the square code a phone camera scans).

SITE below is the ONE place the page's own address is written for the page. qr.js
carries it to the page twice: as the QR grid, and as the text printed under the
code and on the card, so the two can never drift apart.

Error correction level Q (about a quarter of the code can be damaged and it still
scans), the smallest QR version that holds the address, byte mode. The grid has
no margin; the page draws the 4-module white margin itself.

Needs the segno QR library. Run from the repository:
  python3 tools/build_qr.py          (writes qr.js at the repo root)
"""
import json, pathlib

SITE = "https://mrbam-codes.github.io/morning-brief/"

ROOT = pathlib.Path(__file__).resolve().parent.parent


def label(url):
    """The address as people read it: no https://, no closing slash."""
    return url.split("://", 1)[-1].rstrip("/")


def grid(url):
    import segno
    q = segno.make(url, error="q", boost_error=False, micro=False, mode="byte")
    assert q.error == "Q", q.error
    rows = ["".join("1" if m else "0" for m in row) for row in q.matrix]
    assert len(rows) == 17 + 4 * q.version and all(len(r) == len(rows) for r in rows)
    return q.version, rows


def build():
    version, rows = grid(SITE)
    body = ",\n".join("  " + json.dumps(r) for r in rows)
    js = ("/* qr.js: the share card's QR code and the page address.\n"
          "   GENERATED by tools/build_qr.py from its SITE constant. Do not edit by hand.\n"
          "   To change the address: edit SITE in tools/build_qr.py, then run\n"
          "   python3 tools/build_qr.py (needs the segno library) and python3 tests/test_qr.py.\n"
          "   QR version " + str(version) + ", error correction Q, " + str(len(rows)) + " by " + str(len(rows)) +
          " modules, '1' = dark, no margin. */\n"
          'window.MBQR={"url":' + json.dumps(SITE) + ',"label":' + json.dumps(label(SITE)) +
          ',"version":' + str(version) + ',"ecc":"Q","size":' + str(len(rows)) + ',"rows":[\n' + body + "\n]};\n")
    (ROOT / "qr.js").write_text(js, encoding="utf-8")
    print("wrote qr.js:", SITE, "version", version, len(rows), "modules")


if __name__ == "__main__":
    build()
