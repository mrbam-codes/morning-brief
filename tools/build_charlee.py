"""Build charlee.js from the pixel-art Charlee fragment in tools/charlee/c08.html.

Charlee is the second cat. On this page she only ever appears as the pilot in the
share card's spaceship, taking turns with Kimchi, so this file holds one small
drawing and nothing else. kimchi.js is left alone.

The page's Content Security Policy allows only script files from 'self', so the
fragment's inline script is turned into a function here.

Run: python3 tools/build_charlee.py   (writes charlee.js at the repo root)
"""
import json, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
FID = "c08"
# Her head and ruff inside the 140x160 portrait: x, y, w, h (the ship's round window shows the middle of it)
CROP = [2, -10, 117, 133]
SIZE = [140, 160]

raw = (ROOT / "tools" / "charlee" / f"{FID}.html").read_text(encoding="utf-8")
css = "\n".join(re.findall(r"<style>(.*?)</style>", raw, re.S)).strip()
scripts = re.findall(r"<script>(.*?)</script>", raw, re.S)
html = re.sub(r"<style>.*?</style>|<script>.*?</script>", "", raw, flags=re.S).strip()
assert len(scripts) == 1 and f'id="{FID}"' in html


def sub1(s, old, new):
    assert s.count(old) == 1, (old, s.count(old))
    return s.replace(old, new)


js = scripts[0].strip()
js = sub1(js, "document.getElementById('%s')" % FID, "root")
js = sub1(js, "window.matchMedia&&window.matchMedia('(prefers-reduced-motion: reduce)').matches", "K.reduce")
js, n = re.subn(r"(?<![\w.])setTimeout\(", "K.st(", js)
assert n == 3, n
m = re.match(r"\(function\(\)\{(.*)\}\)\(\);?\s*$", js, re.S)
assert m and "getElementById" not in js and "matchMedia" not in js
# the page already styles .hero (the opening animation); keep Charlee out of it
html = sub1(html, 'class="hero"', 'class="khero"')
assert ".hero" not in css
# the share card styles every canvas inside it as its faded background net (.e canvas); keep hers in front and solid
css += "\n#c08 canvas{position:static;z-index:auto;opacity:1}"

out = """/* Charlee, a Maine Coon, a brown tabby, in pixel art: the share card's second pilot.
   GENERATED by tools/build_charlee.py from tools/charlee/c08.html. Do not edit by hand.
   Static asset owned by main: the daily routine never writes this file.
   She blinks now and then, stops when her card leaves the page, and honours prefers-reduced-motion. */
(function(){
'use strict';
var CSS=%s,HTML=%s,CROP=%s,SIZE=%s;
var run=function(root,K){%s};
/* a small head-and-ruff window onto the portrait, w pixels wide */
function cameo(host,w){
  if(!document.getElementById('ccss-%s')){var st=document.createElement('style');st.id='ccss-%s';st.textContent=CSS;document.head.append(st)}
  var s=w/CROP[2],inner=document.createElement('div');
  inner.className='kscene';inner.style.cssText='position:absolute;left:'+(-CROP[0]*s)+'px;top:'+(-CROP[1]*s)+'px;width:'+(SIZE[0]*s)+'px;height:'+(SIZE[1]*s)+'px';
  host.style.width=w+'px';host.style.height=Math.round(w*CROP[3]/CROP[2])+'px';host.textContent='';host.append(inner);
  inner.innerHTML=HTML;
  var K={reduce:matchMedia('(prefers-reduced-motion: reduce)').matches,st:function(fn,ms){return setTimeout(function(){if(host.isConnected)fn()},ms)}};
  try{run(inner.querySelector('#%s'),K)}catch(e){return false}
  return true}
window.CHARLEE={cameo:cameo};
})();
""" % (json.dumps(css), json.dumps(html), json.dumps(CROP), json.dumps(SIZE), m.group(1), FID, FID, FID)
(ROOT / "charlee.js").write_text(out, encoding="utf-8")
print(f"charlee.js: {len(out):,} bytes")
